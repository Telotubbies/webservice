"""Regenerate the mock's static fixtures from their sources of truth.

    .venv/Scripts/python web/mock/gen-fixtures.py     (repo root; the backend venv,
                                                      app.vision.material needs pydantic)

data/tags.ts           <- edge-bridge/tags.yaml (sim registry + modbus map)
data/plantKinds.ts     <- backend/app/plant/kinds.py (KINDS, served by /api/v1/plant-kinds)
data/materialSchema.ts <- backend/app/vision/material.py schema() (/api/v1/vision/material-schema)

Emitted as TypeScript modules (not JSON) so the Vite config bundle and tsc
both import them with no JSON-module or runtime-fs setup.
"""

import importlib.util
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "data"
UNITS = {"degC": "°C", "m3": "m³", "m3/h": "m³/h", "bool": None}
NL = "\n"

SPEC_TYPE = NL.join([
    "export interface TagSpec {",
    "  tail: string; type: 'bool' | 'number'; unit?: string; writable: boolean;",
    "  initial?: number | boolean; min?: number; max?: number; behavior?: string;",
    "  modbus?: { address: string; type: string; writable?: boolean; scale?: number; min?: number; max?: number };",
    "}",
])


def tags() -> list[dict]:
    y = yaml.safe_load((ROOT / "edge-bridge/tags.yaml").read_text(encoding="utf-8"))
    modbus = (y.get("modbus") or {}).get("tags") or {}
    out = []
    for tail, m in y["sim"]["tags"].items():
        unit = m.get("unit")
        kind = "bool" if unit == "bool" or isinstance(m.get("initial"), bool) else "number"
        row = {
            "tail": tail, "type": kind, "unit": UNITS.get(unit, unit),
            "writable": bool(m.get("writable")), "initial": m.get("initial"),
            "min": m.get("min"), "max": m.get("max"), "behavior": m.get("behavior"),
            "modbus": modbus.get(tail),
        }
        out.append({k: v for k, v in row.items() if v is not None})
    return out


def kinds() -> dict:
    spec = importlib.util.spec_from_file_location("kinds", ROOT / "backend/app/plant/kinds.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.KINDS


def material_schema() -> dict:
    import sys
    sys.path.insert(0, str(ROOT / "backend"))
    from app.vision import material  # noqa: PLC0415 - needs the backend on sys.path
    return material.schema()


def module(src: str, body: str) -> str:
    return "// GENERATED by web/mock/gen-fixtures.py from " + src + " - do not edit by hand." + NL + NL + body + NL


def main() -> None:
    OUT.mkdir(exist_ok=True)
    t = tags()
    k = kinds()
    (OUT / "tags.ts").write_text(module(
        "edge-bridge/tags.yaml",
        SPEC_TYPE + NL + NL + "export const TAG_SPECS: TagSpec[] = " + json.dumps(t, ensure_ascii=False, indent=1) + ";",
    ), encoding="utf-8")
    (OUT / "plantKinds.ts").write_text(module(
        "backend/app/plant/kinds.py",
        "export const PLANT_KINDS: Record<string, unknown> = " + json.dumps(k, ensure_ascii=False, indent=1) + ";",
    ), encoding="utf-8")
    (OUT / "materialSchema.ts").write_text(module(
        "backend/app/vision/material.py",
        "export const MATERIAL_SCHEMA = " + json.dumps(material_schema(), ensure_ascii=False, indent=1) + ";",
    ), encoding="utf-8")
    print(f"{len(t)} tags, {len(k)} kinds, material schema")


if __name__ == "__main__":
    main()
